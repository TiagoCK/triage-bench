"""Render results/latest.json as Markdown tables, one per (task, repo, subset)."""

from __future__ import annotations

from itertools import groupby

LABEL_COLS = [
    ("micro_f1", "micro F1"),
    ("macro_f1", "macro F1"),
    ("micro_precision", "P"),
    ("micro_recall", "R"),
]
DUP_COLS = [
    ("recall@1", "R@1"),
    ("recall@5", "R@5"),
    ("mrr@10", "MRR@10"),
    ("average_precision", "AP"),
    ("recall@p90", "R@P90"),
    ("recall", "flag R"),
    ("precision@base_rate", "P@base"),
    ("false_dup_rate", "false-dup rate"),
]
OPS_COLS = [("usd_per_1k", "$/1k issues"), ("p50_latency_s", "p50 s"), ("p95_latency_s", "p95 s")]


def render(rows: list[dict]) -> str:
    out = [
        "# Results",
        "",
        "Generated by `triage eval` / `triage report`. Do not edit by hand.",
        "",
        "Brackets are 95% bootstrap confidence intervals over test issues. When two systems'",
        "intervals overlap heavily, the test set cannot tell them apart.",
        "",
    ]
    order = lambda r: (r["task"], r["repo"], r["subset"])  # noqa: E731
    for (task, repo, subset), group in groupby(sorted(rows, key=order), key=order):
        group = sorted(group, key=lambda r: (r["model"] != "-", r["system"], r["model"]))
        cols = (LABEL_COLS if task == "labels" else DUP_COLS) + OPS_COLS
        cols = [c for c in cols if any(r.get(c[0]) is not None for r in group)]
        n = int(max(r.get("n", 0) for r in group))
        out.append(f"## {task}: {repo} ({subset}, n={n})")
        out.append("")
        out.append("| system | model | " + " | ".join(h for _, h in cols) + " |")
        out.append("|---|---|" + "---:|" * len(cols))
        for r in group:
            cells = [_fmt(r.get(k), r.get(f"{k}_ci")) for k, _ in cols]
            out.append(f"| {r['system']} | {r['model']} | " + " | ".join(cells) + " |")
        out.append("")
    return "\n".join(out)


def _fmt(v, ci=None) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        text = f"{v:.3f}"
        if ci:
            text += f" [{ci[0]:.2f}, {ci[1]:.2f}]"
        return text
    return str(v)
